-- CITI-Senti: Initial PostgreSQL schema for Supabase
-- Source: Updated DBML provided on 2026-11-23
-- Intended to run once as a Supabase CLI migration.
-- Table names use lowercase snake_case to avoid quoted identifiers in Python/SQL.
-- Business rule: analysis_results stores the CURRENT set of results for each
-- submission; FastAPI must invalidate/delete old results when comments change.
-- This migration does not create administrators or seed research categories.

BEGIN;

-- 1. Enumerations
CREATE TYPE public.feedback_analysis_status AS ENUM (
    'pending', 'processing', 'completed', 'failed'
);

CREATE TYPE public.feedback_moderation_status AS ENUM (
    'pending_review', 'approved', 'flagged', 'hidden'
);

CREATE TYPE public.sentiment_type AS ENUM (
    'positive', 'neutral', 'negative'
);

-- 2. Administrators
CREATE TABLE public.admin_users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(100) NOT NULL UNIQUE,
    full_name varchar(200) NOT NULL,
    password_hash varchar(255) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Policy topics
CREATE TABLE public.policy_topics (
    topic_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_name varchar(200) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

-- 4. Research aspect categories
CREATE TABLE public.aspect_categories (
    aspect_code varchar(3) PRIMARY KEY,
    aspect_name varchar(150) NOT NULL UNIQUE,
    description text NOT NULL,
    example_text text,
    CONSTRAINT chk_aspect_code CHECK (
        aspect_code IN (
            'A01', 'A02', 'A03', 'A04', 'A05', 'A06',
            'A07', 'A08', 'A09', 'A10', 'A11'
        )
    )
);

-- 5. Consent-based citizen feedback storage
CREATE TABLE public.feedback_submissions (
    submission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_code varchar(50) NOT NULL UNIQUE,

    original_comment varchar(1000) NOT NULL,
    current_comment varchar(1000) NOT NULL,
    comment_revision integer NOT NULL DEFAULT 1,

    topic_id bigint,
    citizen_policy_reference varchar(255),
    standardized_policy_name varchar(255),
    self_reported_language varchar(30),

    storage_consent_at timestamptz NOT NULL,
    consent_notice_version varchar(50) NOT NULL,

    submitted_at timestamptz NOT NULL DEFAULT now(),
    edited_at timestamptz,

    access_code_hash varchar(255) NOT NULL,

    analysis_status public.feedback_analysis_status NOT NULL DEFAULT 'pending',
    analysis_error text,
    analyzed_at timestamptz,
    model_version varchar(100),

    moderation_status public.feedback_moderation_status NOT NULL DEFAULT 'pending_review',

    CONSTRAINT fk_feedback_topic FOREIGN KEY (topic_id)
        REFERENCES public.policy_topics(topic_id) ON DELETE SET NULL,
    CONSTRAINT chk_comment_revision CHECK (comment_revision >= 1),
    CONSTRAINT chk_original_comment CHECK (
        char_length(btrim(original_comment)) BETWEEN 1 AND 1000
    ),
    CONSTRAINT chk_current_comment CHECK (
        char_length(btrim(current_comment)) BETWEEN 1 AND 1000
    ),
    CONSTRAINT chk_self_reported_language CHECK (
        self_reported_language IS NULL
        OR self_reported_language IN (
            'English', 'Tagalog', 'Ilocano', 'Code-Switched', 'Not Specified'
        )
    )
);

-- 6. Latest per-aspect NLP predictions
CREATE TABLE public.analysis_results (
    submission_id bigint NOT NULL,
    aspect_code varchar(3) NOT NULL,
    sentiment_label public.sentiment_type,  -- Nullable per the supplied DBML
    comment_revision integer NOT NULL,

    CONSTRAINT pk_analysis_results PRIMARY KEY (submission_id, aspect_code),
    CONSTRAINT fk_analysis_submission FOREIGN KEY (submission_id)
        REFERENCES public.feedback_submissions(submission_id) ON DELETE CASCADE,
    CONSTRAINT fk_analysis_aspect FOREIGN KEY (aspect_code)
        REFERENCES public.aspect_categories(aspect_code) ON DELETE RESTRICT,
    CONSTRAINT chk_result_comment_revision CHECK (comment_revision >= 1)
);

-- 7. Moderator actions / audit trail
CREATE TABLE public.feedback_reviews (
    review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id bigint NOT NULL,
    admin_user_id bigint NOT NULL,
    action_type varchar(50) NOT NULL,
    previous_value text,
    new_value text,
    review_note text,
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_review_submission FOREIGN KEY (submission_id)
        REFERENCES public.feedback_submissions(submission_id) ON DELETE CASCADE,
    CONSTRAINT fk_review_admin FOREIGN KEY (admin_user_id)
        REFERENCES public.admin_users(user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_review_action_type CHECK (
        action_type IN ('approve', 'flag', 'hide', 'policy_update')
    )
);

-- 8. Practical indexes for admin queue, reporting, and FK lookups
CREATE INDEX idx_feedback_topic_id
    ON public.feedback_submissions(topic_id);
CREATE INDEX idx_feedback_analysis_status
    ON public.feedback_submissions(analysis_status);
CREATE INDEX idx_feedback_moderation_submitted_at
    ON public.feedback_submissions(moderation_status, submitted_at DESC);
CREATE INDEX idx_feedback_submitted_at
    ON public.feedback_submissions(submitted_at DESC);
CREATE INDEX idx_analysis_aspect_code
    ON public.analysis_results(aspect_code);
CREATE INDEX idx_feedback_reviews_submission_created_at
    ON public.feedback_reviews(submission_id, created_at DESC);
CREATE INDEX idx_feedback_reviews_admin_user_id
    ON public.feedback_reviews(admin_user_id);

-- 9. Security-in-depth: do not expose private tables via Supabase Data API.
-- The application is designed for React -> FastAPI -> PostgreSQL.
-- FastAPI's controlled PostgreSQL connection must enforce authorization.
ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.policy_topics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.aspect_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feedback_submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analysis_results ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feedback_reviews ENABLE ROW LEVEL SECURITY;

-- No RLS policies are created: anon/authenticated Data API access is denied.
-- Revoke any default grants on these six tables from API roles.
REVOKE ALL ON TABLE public.admin_users FROM anon, authenticated, service_role;
REVOKE ALL ON TABLE public.policy_topics FROM anon, authenticated, service_role;
REVOKE ALL ON TABLE public.aspect_categories FROM anon, authenticated, service_role;
REVOKE ALL ON TABLE public.feedback_submissions FROM anon, authenticated, service_role;
REVOKE ALL ON TABLE public.analysis_results FROM anon, authenticated, service_role;
REVOKE ALL ON TABLE public.feedback_reviews FROM anon, authenticated, service_role;

COMMIT;
